/** 説明つきの言葉。説明は GLOSSARY から引くか、explain で直接渡す */
export function Term({ children, k, explain }: { children?: ReactNode; k?: string; explain?: string }) {
  const word = k ?? (typeof children === 'string' ? children : '');
  const text = explain ?? GLOSSARY[word];
  if (!text) return <>{children ?? word}</>;
  return (
    <span className="term" tabIndex={0} data-tip={text} aria-label={`${word}：${text}`}>
      {children ?? word}
    </span>
  );
}
